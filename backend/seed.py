async def seed():
    """幂等写入：逐条 INSERT OR IGNORE（已有食物跳过、新增食物自动补齐）；无画像时创建默认画像"""
    conn = await db.get_conn()
    try:
        # 增量补齐食物库：已存在的忽略，新加的食材自动写入
        await conn.executemany(
            "INSERT OR IGNORE INTO food_standards (food_name, aliases, kcal, protein, fat, carbs, sodium) VALUES (?, ?, ?, ?, ?, ?, ?)",
            FOOD_STANDARDS)
        # 默认用户画像（首次启动自动创建，demo 无需注册登录）
        async with conn.execute("SELECT COUNT(*) AS c FROM profiles WHERE username = 'demo'") as cur:
            row = await cur.fetchone()
        if (row["c"] if hasattr(row, "keys") else row[0]) == 0:
            await conn.execute(
                "INSERT INTO profiles (username, gender, age, height, weight, goal, activity_level) VALUES ('demo', '男', 25, 170, 65, '保持健康', '轻量运动')")
        await conn.commit()
    finally:
        await conn.close()
